export type TranslationKey = keyof typeof translations.id;

/**
 * Custom React hook for client-side and server-side synchronized translations.
 */
export function useTranslation() {
    const { props } = usePage<{ locale?: string }>();

    // Initial locale resolution: prop -> localStorage -> default 'id'
    const [locale, setLocaleState] = useState<Locale>(() => {
        if (typeof window !== 'undefined') {
            const stored = localStorage.getItem('aromapalace_locale');
            if (stored === 'id' || stored === 'en') {
                return stored;
            }
        }
        return (props?.locale === 'en' ? 'en' : 'id') as Locale;
    });

    // Keep state in sync if Inertia page prop updates
    useEffect(() => {
        if (props?.locale && (props.locale === 'id' || props.locale === 'en')) {
            setLocaleState(props.locale as Locale);
            if (typeof window !== 'undefined') {
                localStorage.setItem('aromapalace_locale', props.locale);
            }
        }
    }, [props?.locale]);

    /**
     * Switch language between 'id' and 'en'
     */
    const setLanguage = useCallback((newLocale: Locale) => {
        setLocaleState(newLocale);
        if (typeof window !== 'undefined') {
            localStorage.setItem('aromapalace_locale', newLocale);
            document.cookie = `locale=${newLocale};path=/;max-age=31536000;SameSite=Lax`;
        }

        router.post('/locale', { locale: newLocale }, {
            preserveScroll: true,
            preserveState: true,
        });
    }, []);

    /**
     * Get translation text by key with optional variable replacements
     */
    const t = useCallback((key: TranslationKey | string, params?: Record<string, string | number>): string => {
        const dict = translations[locale] || translations.id;
        // @ts-expect-error key may be dynamic
        let text = dict[key] || translations.id[key] || key;

        if (params) {
            Object.entries(params).forEach(([paramKey, val]) => {
                text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
            });
        }

        return text;
    }, [locale]);

    /**
     * Helper to pick between Indonesian and English string fields with automatic fallback
     */
    const pickText = useCallback((idText: string | null | undefined, enText: string | null | undefined): string => {
        if (locale === 'en' && enText && enText.trim() !== '') {
            return enText;
        }
        return idText || '';
    }, [locale]);

    return {
        locale,
        isEn: locale === 'en',
        isId: locale === 'id',
        t,
        pickText,
        setLanguage,
    };
}

/**
 * Localizes perfume category names based on active locale
 */
export function formatCategoryName(name?: string | null, isEn?: boolean): string {
    if (!name) return '';
    if (!isEn) return name;
    const lower = name.toLowerCase().trim();
    if (lower === 'all' || lower === 'semua' || lower === 'semua kategori') return 'All Categories';
    if (lower === 'parfum pria' || lower === 'pria' || lower === "men's perfume" || lower === 'men') return "Men's Perfume";
    if (lower === 'parfum wanita' || lower === 'wanita' || lower === "women's perfume" || lower === 'women') return "Women's Perfume";
    if (lower === 'unisex' || lower === 'unisex fragrance') return 'Unisex Fragrance';
    if (lower === 'discovery' || lower.includes('discovery set')) return 'Discovery Sets & Vials';
    if (lower.includes('attar')) return 'Artisanal Attar';
    return name;
}

